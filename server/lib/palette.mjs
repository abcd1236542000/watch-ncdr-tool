/* [R,G,B, mm下限, mm上限(null=無上限), 等級]
   等級: 0無雨 1零星/毛雨 2小雨 3中雨 4大雨 5豪雨
   ⚠️ 白色 (255,255,255) 在雨量圖中是**最低階 0mm**，不是豪雨。 */
export const PAL = [
  [255, 255, 255, 0, 0.1, 0],
  [152, 255, 255, 0.1, 0.3, 1],
  [0, 206, 255, 0.3, 1, 2],
  [0, 154, 255, 0.3, 1, 2],
  [0, 106, 247, 1, 1.5, 2],
  [46, 156, 0, 1, 1.5, 2],
  [43, 255, 0, 1.5, 3, 3],
  [254, 254, 8, 1.5, 3, 3],
  [255, 203, 0, 3, 6, 3],
  [255, 156, 0, 3, 6, 3],
  [254, 0, 5, 6, 10, 4],
  [201, 2, 0, 6, 10, 4],
  [157, 0, 0, 10, 17, 4],
  [154, 0, 157, 10, 17, 4],
  [207, 0, 215, 17, 25, 5],
  [255, 0, 247, 17, 25, 5],
  [254, 203, 255, 25, null, 5]
];

export const LV = ['無雨', '零星/毛雨', '小雨', '中雨', '大雨', '豪雨'];

/* 最近色距離門檻，超過視為非資料像素（地名文字、界線、反鋸齒過渡色） */
const MAXD2 = 60 * 60;

/* [v1.4] mm 範圍每兩個色帶一階（色階列標籤每 2 個 band 出現一次）。
   v1.3 以前對未標籤 band 用內插推估是錯的。 */
export function bandRange(i) {
  const p = PAL[i];
  return p[4] === null ? `≥${p[3]}mm` : `${p[3]}~${p[4]}mm`;
}

export function classify(r, g, b, a) {
  if (a < 30) return { lv: 0, mm: 0, hit: false };
  let bi = -1, bd = 1e9;
  for (let i = 0; i < PAL.length; i++) {
    const dr = r - PAL[i][0], dg = g - PAL[i][1], db = b - PAL[i][2];
    const d = dr * dr + dg * dg + db * db;
    if (d < bd) { bd = d; bi = i; }
  }
  if (bd > MAXD2) return { lv: 0, mm: 0, hit: false };
  return { lv: PAL[bi][5], mm: PAL[bi][3], hit: true, band: bi };
}
